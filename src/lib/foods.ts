export const BUILTIN_FOODS: (FoodItem & { keywords: string })[] = RAW.map(([name, amount, kcal, p, f, c, kw]) => ({
  name,
  amount,
  kcal,
  proteinG: p,
  fatG: f,
  carbG: c,
  source: "builtin",
  keywords: `${name} ${kw ?? ""}`,
}));

const kataToHira = (s: string) => s.replace(/[\u30a1-\u30f6]/g, (c) => String.fromCharCode(c.charCodeAt(0) - 0x60));

export function searchBuiltin(q: string, limit = 12): FoodItem[] {
  const query = kataToHira(q.trim().toLowerCase());
  if (!query) return BUILTIN_FOODS.slice(0, limit);
  return BUILTIN_FOODS.filter((f) => kataToHira(f.keywords.toLowerCase()).includes(query)).slice(0, limit);
}
